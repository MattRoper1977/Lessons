/* Stamp tools/liveteach/picker_source.js into the projector and teacher views
   between the MBM-LIVETEACH-PICKER markers — the same pinned-region pattern as
   the core, the splash and the QR encoder. Edit the source, run this; never a
   stamped copy.

     node tools/liveteach/stamp_picker.mjs            rewrite the stamped regions
     node tools/liveteach/stamp_picker.mjs --check    exit 1 on drift (CI mode)
     node tools/liveteach/stamp_picker.mjs --self-test prove --check can fail */
import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const ROOT = path.resolve(HERE, '..', '..');
const SOURCE = path.join(HERE, 'picker_source.js');
const VIEWS = ['liveteach/projector.html', 'liveteach/teacher.html'];
const BEGIN = '<!-- MBM-LIVETEACH-PICKER:BEGIN generated by tools/liveteach/stamp_picker.mjs from tools/liveteach/picker_source.js — do not edit by hand -->';
const END = '<!-- MBM-LIVETEACH-PICKER:END -->';

function region() {
  return BEGIN + '\n<script>\n' + fs.readFileSync(SOURCE, 'utf8') + '</script>\n' + END;
}
function check(files) {
  const reg = region();
  const bad = [];
  for (const rel of files) {
    const p = path.join(ROOT, rel);
    if (!fs.existsSync(p)) { bad.push(rel + ': MISSING FILE'); continue; }
    const html = fs.readFileSync(p, 'utf8');
    const a = html.indexOf(BEGIN), b = html.indexOf(END);
    if (a === -1 || b === -1) { bad.push(rel + ': NO PICKER REGION'); continue; }
    if (html.slice(a, b + END.length) !== reg) bad.push(rel + ': PICKER REGION DRIFTED');
  }
  return bad;
}

const MODE = process.argv[2] || '';
if (MODE === '--check') {
  const bad = check(VIEWS);
  if (bad.length) { bad.forEach(b => console.log('[FAIL] ' + b)); process.exit(1); }
  console.log('[OK] both stamped picker regions match picker_source.js byte-for-byte');
} else if (MODE === '--self-test') {
  const tmp = fs.mkdtempSync(path.join(HERE, 'selftest-'));
  try {
    const rel = path.join(path.basename(tmp), 'view.html');
    /* Perturb the P2 guarantee itself: a floor under the weight is exactly
       the defect the correction exists to kill, so that is the byte the
       drift gate must notice. */
    fs.writeFileSync(path.join(HERE, rel), region().replace('return st.since[i];', 'return Math.max(0.05, st.since[i]);'));
    const bad = check([path.join('tools/liveteach', rel)]);
    if (bad.length === 1 && /DRIFTED/.test(bad[0])) console.log('[SELF-TEST] PASS — a re-introduced min-weight floor is detected');
    else { console.log('[SELF-TEST] FAIL'); process.exit(1); }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
} else {
  const reg = region();
  for (const rel of VIEWS) {
    const p = path.join(ROOT, rel);
    let html = fs.readFileSync(p, 'utf8');
    const a = html.indexOf(BEGIN), b = html.indexOf(END);
    if (a !== -1 && b !== -1) html = html.slice(0, a) + reg + html.slice(b + END.length);
    else html = html.replace('<!-- MBM-LIVETEACH-CORE:BEGIN', reg + '\n<!-- MBM-LIVETEACH-CORE:BEGIN');
    fs.writeFileSync(p, html);
    console.log('[STAMPED] ' + rel);
  }
}
