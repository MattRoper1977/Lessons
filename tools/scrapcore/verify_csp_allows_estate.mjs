/* ---- serve it -------------------------------------------------------------- */
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css',
               '.json': 'application/json', '.png': 'image/png', '.svg': 'image/svg+xml', '.ico': 'image/x-icon' };
function serve(dir) {
  const s = http.createServer((req, res) => {
    let rel = decodeURIComponent(req.url.split('?')[0]);
    if (rel.endsWith('/')) rel += 'index.html';
    const file = path.join(dir, rel);
    if (!file.startsWith(dir) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { 'Content-Type': MIME[path.extname(file)] || 'application/octet-stream' });
    fs.createReadStream(file).pipe(res);
  });
  return new Promise(r => s.listen(0, '127.0.0.1', () => r({ s, base: `http://127.0.0.1:${s.address().port}` })));
}
const { s: server, base: BASE } = await serve(SCRATCH);
const browser = await chromium.launch();

async function visit(url, { descend = false } = {}) {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const pg = await ctx.newPage();
  const errs = [], blocked = [];
  pg.on('pageerror', e => errs.push(String(e).slice(0, 140)));
  pg.on('requestfailed', r => blocked.push(new URL(r.url()).pathname + ' :: ' + ((r.failure() || {}).errorText || '')));
  await pg.addInitScript(() => {
    window.__csp = [];
    document.addEventListener('securitypolicyviolation', e =>
      window.__csp.push({ directive: e.violatedDirective, blocked: e.blockedURI, sample: (e.sample || '').slice(0, 40) }));
  });
  await pg.goto(url, { waitUntil: 'load', timeout: 45000 });
  await pg.waitForTimeout(2000);
  if (descend) {
    /* one live descent, driven through the page's own controls */
    await pg.evaluate(async () => {
      const sleep = ms => new Promise(r => setTimeout(r, ms));
      const hit = sel => { const e = document.querySelector(sel); if (e) { e.click(); return true; } return false; };
      for (const s of ['#startBtn', '#launchBtn', '[data-action="launch"]', 'button']) if (hit(s)) break;
      await sleep(1500);
      for (const k of ['ArrowRight', 'ArrowDown', 'Space']) {
        window.dispatchEvent(new KeyboardEvent('keydown', { key: k === 'Space' ? ' ' : k, bubbles: true }));
        await sleep(300);
        window.dispatchEvent(new KeyboardEvent('keyup', { key: k === 'Space' ? ' ' : k, bubbles: true }));
      }
      await sleep(1200);
    }).catch(() => {});
    await pg.waitForTimeout(800);
  }
  const csp = await pg.evaluate(() => window.__csp || []);
  const exitMounted = await pg.evaluate(() => !!window.__mbmExit);
  const painted = await pg.evaluate(() => {
    const c = document.querySelector('canvas'); if (!c) return null;
    const g = c.getContext('2d') || c.getContext('webgl') || c.getContext('webgl2');
    if (!g || !g.getImageData) return 'non-2d context';
    const w = Math.min(c.width, 400), h = Math.min(c.height, 300);
    const d = g.getImageData(0, 0, w, h).data;
    let lit = 0; for (let i = 0; i < d.length; i += 4) if (d[i] + d[i + 1] + d[i + 2] > 30) lit++;
    return lit;
  }).catch(() => null);
  await ctx.close();
  return { csp, errs, blocked, exitMounted, painted };
}

/* ---- the assertion ---------------------------------------------------------- */
