/* ---- THE PLANTED FAILURE.
 * The ruling is "no 'self', because nothing needs it". The way to prove that
 * gate can go red on the real target is to give it something that does need it:
 * put /hud.js back in and the CSP must visibly block it. If this passes, the
 * CSP is not doing anything and the whole ruling is worthless. */
{
  const p = path.join(SCRATCH, 'scrapcore', 'index.html');
  const clean = fs.readFileSync(p, 'utf8');
  const injected = clean.replace('</body>', `${cov.scriptLine}\n</body>`);
  if (injected === clean) throw new Error('planted failure could not be inserted — no </body>');
  fs.writeFileSync(p, injected);
  const planted = await visit(BASE + '/scrapcore/');
  fs.writeFileSync(p, clean);
  const restored = await visit(BASE + '/scrapcore/');

  const blockedScript = planted.csp.some(v => /script-src/.test(v.directive) && /hud\.js/.test(v.blocked))
                     || planted.blocked.some(b => /hud\.js/.test(b));
  row('P0.3g', 'PLANTED FAILURE: reinstating <script src="/hud.js"> is BLOCKED by the shipped CSP',
    blockedScript,
    `violations ${JSON.stringify(planted.csp)} · failed requests ${JSON.stringify(planted.blocked.filter(b => /hud/.test(b)))}`);
  row('P0.3h', 'and removing it again restores a clean run — the gate is not stuck red',
    restored.csp.length === 0 && restored.exitMounted === true,
    `violations ${restored.csp.length}, exit mounted ${restored.exitMounted}`);
}

