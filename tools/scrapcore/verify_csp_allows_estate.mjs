/* A-P0.3 — the CSP control.
 *
 * P0.1 measured what the estate injects. The answer decided P0.2:
 *
 *   NO game route on this site ships its own CSP, so Scrap Core's would be the
 *   first. /hud.js is requested by 12 of 23 root game routes. ELEVEN request no
 *   same-origin subresource at all — including /emberwild/ and /relicforge/,
 *   which give the player a way out through the estate's own generated INLINE
 *   EXIT REGION instead. data/hud-coverage.json says why that exists in as many
 *   words: "No src, no dependency, no request: the single-file promise these
 *   games make is intact."
 *
 * So the ruling is KEEP THE CSP AS SHIPPED. Not one directive is widened,
 * because on this route not one directive has a measured consumer — and P0.2
 * says a directive widened without a named consumer is a fault, not a fix.
 *
 * This gate proves that decision holds in a browser on the served page, and it
 * carries the planted failure that makes it a control rather than a claim: put
 * /hud.js back in, and the CSP must visibly BLOCK it.
 */
